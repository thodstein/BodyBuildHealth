/**
 * bb-hub-zones.ts — цвета зон «ББ-диагностики» (общие для хаба и его секций).
 *
 * Один источник, потому что панель объёма, карточка «что делать дальше» и
 * эффект коррекции красят одинаковые зоны (`green`/`yellow`/`red`/`nodata`).
 * Важно: «нет данных» — серый, а не зелёный (BB-G-01: nodata ≠ «всё хорошо»).
 */

/** Текст/граница зоны. Неизвестная зона — серый, а не «успех». */
export const vrZoneColor = (z: string): string =>
  z === 'red' ? '#ef4444' : z === 'yellow' ? '#f59e0b' : z === 'green' ? '#22c55e' : '#9ca3af';

/** Заливка зоны (низкая насыщенность — читаемо на тёмной теме). */
export const vrZoneBg = (z: string): string =>
  z === 'red'
    ? 'rgba(239,68,68,0.10)'
    : z === 'yellow'
      ? 'rgba(245,158,11,0.10)'
      : z === 'green'
        ? 'rgba(34,197,94,0.08)'
        : 'rgba(148,163,184,0.08)';
