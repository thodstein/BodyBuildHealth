/**
 * Дата бланка при ручном вводе анализов.
 *
 * Проход 157: каталог и расширенная панель сохраняли `new Date().toISOString()` —
 * дату ввода, а не дату бланка. Дата решает, какой бланк считается текущим
 * (проходы 136/151) и какие точки попадают в «до курса → середина → после ПКТ»,
 * поэтому анализ, сданный месяц назад и введённый сегодня, вставал в «сегодня» и
 * сдвигал динамику. Плюс `toISOString()` — UTC: вечером в восточных часовых поясах
 * это соседний день, а не дата на календаре человека.
 *
 * Одно правило на все поверхности ручного ввода: дату выбирает человек, пустая
 * означает «сегодня».
 */

/** Сегодняшняя дата в местном времени — как её видит человек в календаре. */
export function todayLabDate(now: Date = new Date()): string {
  const y = now.getFullYear();
  const m = String(now.getMonth() + 1).padStart(2, '0');
  const d = String(now.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

/**
 * Дата, которая станет записью: выбранная человеком, а пустая — сегодня.
 *
 * `input[type=date]` отдаёт `YYYY-MM-DD` или пустую строку (поле очистили);
 * сохранять пустую дату нельзя — без неё запись не выигрывает сравнение по дате.
 */
export function labEntryDate(chosen: string, now?: Date): string {
  const t = String(chosen ?? '').trim();
  return /^\d{4}-\d{2}-\d{2}$/.test(t) ? t : todayLabDate(now);
}
