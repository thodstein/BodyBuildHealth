/** Сумма FG: каждая зона 0–4 (округление, кламп); игнорирует null/NaN. */
export function ferrimanGallweyTotal(scores: Array<number | undefined | null>): number {
  const vals = Array.isArray(scores) ? scores.slice(0, FERRIMAN_GALLWEY_ZONES.length) : [];
  let total = 0;
  for (const v of vals) {
    const n = Number(v);
    if (!Number.isFinite(n)) continue;
    total += Math.min(4, Math.max(0, Math.round(n)));
  }
  return total;
}

/** Порог гирсутизма >8 (у части этнических групп >6). Динамика, не диагноз. */
export function ferrimanGallweyBand(total: number, opts: { lessSensitiveCutoff?: boolean } = {}): {
  level: 'ok' | 'borderline' | 'hirsutism';
  label: string;
  advice: string;
} {
  const t = Number.isFinite(total) ? Math.max(0, Math.round(Number(total))) : 0;
  const cutoff = opts.lessSensitiveCutoff ? 6 : 8;
  if (t > cutoff) {
    return {
      level: 'hirsutism',
      label: `🔴 Гирсутизм: ${t} > ${cutoff}`,
      advice: 'Фото локусов, отмена/снижение андрогенов, гинеколог-эндокринолог (исключить СПКЯ/андроген-секретирующие причины); спиронолактон — только врач.',
    };
  }
  if (t >= cutoff - 2) {
    return {
      level: 'borderline',
      label: `🟠 Погранично: ${t} (порог ${cutoff})`,
      advice: 'Еженедельное фото/шкала; при росте — снижение дозы андрогенов.',
    };
  }
  return {
    level: 'ok',
    label: `🟢 Норма: ${t} ≤ ${cutoff}`,
    advice: 'Плановый контроль шкалы раз в 4 нед на курсе.',
  };
}

