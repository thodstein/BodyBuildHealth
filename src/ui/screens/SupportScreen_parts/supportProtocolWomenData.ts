export type FemaleVirilizationResult = {
  score: number;
  band: 'safe' | 'caution' | 'risk' | 'high' | 'critical';
  bandLabel: string;
  breakdown: Array<{ name: string; contribution: number }>;
  recommendations: string[];
};

export function femaleVirilizationScore(
  picks: Array<{ id: string; dose: number }>,
  weeks: number,
  opts: { age?: number; geneticSensitivity?: boolean; previousCycles?: boolean } = {},
): FemaleVirilizationResult {
  const age = Number.isFinite(opts.age) ? Number(opts.age) : 30;
  let ageMult = 1.0;
  if (age < 25) ageMult = 1.3;
  else if (age > 45) ageMult = 0.8;
  else if (age > 35) ageMult = 0.9;
  const sens = 3.0 * ageMult * (opts.geneticSensitivity ? 1.5 : 1.0) * (opts.previousCycles ? 1.2 : 1.0);
  const exposure = Math.max(0.25, (Number.isFinite(weeks) ? Number(weeks) : 0) / 4);

  let total = 0;
  const breakdown: Array<{ name: string; contribution: number }> = [];
  for (const p of picks) {
    const item = FEMALE_VIRILIZATION_CALC.find((x) => x.id === p.id);
    if (!item) continue;
    if (item.contraindicated || item.red <= 0) {
      total = 100;
      breakdown.push({ name: item.name, contribution: 100 });
      continue;
    }
    const dose = Math.max(0, Number(p.dose) || 0);
    const contribution = (dose / item.red) * item.androgenIndex * exposure * sens * 10;
    total += contribution;
    breakdown.push({ name: item.name, contribution });
  }
  total = Math.min(100, Math.max(0, total));
  const score = Math.round(total);

  let band: FemaleVirilizationResult['band'] = 'safe';
  let bandLabel = '🟢 Безопасно';
  let recommendations: string[] = ['Мониторинг каждые 4 недели.'];
  if (score >= 80) {
    band = 'critical'; bandLabel = '🔴 КРИТИЧНО';
    recommendations = ['НЕМЕДЛЕННАЯ ОТМЕНА ВСЕГО', 'Спиронолактон 50 мг/день (врач)', 'Эндокринолог', 'Оценка необратимых изменений'];
  } else if (score >= 60) {
    band = 'high'; bandLabel = '🔴 Высокий риск';
    recommendations = ['Снизить дозу на 50%', 'Спиронолактон 50 мг/д (врач)', 'Финастерид — только врач', 'Рассмотреть отмену'];
  } else if (score >= 40) {
    band = 'risk'; bandLabel = '🟠 Риск';
    recommendations = ['Снизить дозу', 'Спиронолактон 25 мг/д (врач)', 'Мониторинг каждые 2 недели', 'Запись голоса еженедельно'];
  } else if (score >= 20) {
    band = 'caution'; bandLabel = '🟡 Внимание';
    recommendations = ['Усилить защиту (см. примерные протоколы «Поддержка»)', 'Мониторинг голоса/клитора еженедельно'];
  }
  return { score, band, bandLabel, breakdown, recommendations };
}

