/**
 * recipe-content-authoring.test.ts — кампания контента: порции всех рецептов авторские.
 *
 * Дефект (docs/NUTRITION-PLANNER-PRO-AUDIT-2026-10.md §4, остаток «Легаси-дрейф
 * порций»): 23 из 1017 рецепта писались без ingredientIds — декомпозиция падала в
 * парсинг `ingredients`-строк («Яйца 2 шт» → findFoodByName), где часть строк
 * матчилась в МУСОР («Яйца» → «Бараньи яйца» 170 г), а часть получала дефолт по
 * роли (масло 10 г, зелень 30 г). Дальше scaleToRecipeKcal подгонял ккал шапки —
 * итоговый дрейф порций до ±14% (корень промахов рецептурного пути).
 *
 * Решение: ТОЛЬКО контент-правка — у каждого из 23 рецептов появились авторские
 * ingredientIds × portions (граммы из его же `ingredients`-строк), шапка
 * синхронизирована с раскладкой (`syncRecipeHeaderFromDecomposition`), поэтому
 * «показано = съедается», а «⚖️ Порция ×N%» держится в коридоре ±3%.
 *
 * Лок: ни один рецепт без авторской раскладки; дрейф шапки от разбора не растёт.
 *
 * «Было → стало» (шапка kcal/P/F/C 23 рецептов, теперь выведена из разбора):
 *   Овсяноблин с курицей и сыром   440/40/16/34 → 500/46/20/34
 *   Яйца бенедикт с лососем        400/36/24/12 → 415/35/22/19
 *   Бурито для завтрака            480/30/22/44 → 575/31/29/48
 *   Овсянка солёная с яйцом        420/28/20/38 → 375/16/18/37
 *   Куриное филе «Пармезан»        440/52/16/22 → 575/77/24/13
 *   Острая курица по-корейски      380/44/12/26 → 575/65/22/29
 *   Куриный пирог с овощами        380/40/16/20 → 695/80/34/17
 *   Ленивые вареники               360/32/8/44  → 715/66/25/56
 *   Салат Цезарь с курицей         420/48/18/16 → 480/72/14/16
 *   Плов с курицей                 500/42/8/62  → 605/55/17/58
 *   Паста с курицей и грибами      520/42/14/58 → 555/63/19/33
 *   Салат с тунцом, киноа и авокадо 470/38/18/38 → 815/57/43/50
 *   Салат нисуаз фит               380/36/16/22 → 570/52/34/14
 *   Лаваш с тунцом и овощами       380/34/14/32 → 475/44/12/48
 *   Греческий салат с протеином    340/34/18/12 → 525/42/35/10
 *   Паста болоньезе из сои/нут     420/28/10/60 → 385/34/3/56
 *   Белковый смузи                 980/65/35/95 → 880/62/29/93
 *   Протеиновый чизкейк            380/38/14/24 → 505/74/18/12
 *   Протеиновые шарики             320/28/12/32 → 560/40/22/50
 *   Сырные палочки                 260/28/14/6  → 500/45/34/4
 *   Протеиновый кофе               160/28/2/6   → 165/25/3/9
 *   Бананово-белковый пудинг       220/26/8/20  → 365/28/12/36
 *   Снеки из нута                  200/12/8/24  → 525/20/21/64
 */
import { describe, it, expect } from 'vitest';
import { RECIPE_DB } from '../../../../../data/recipe-db';
import { FOOD_DB } from '../../../../../core/nutrition-database';

const FOOD_IDS = new Set(FOOD_DB.map(f => f.id));

describe('кампания контента: все рецепты с авторской раскладкой', () => {
  it('ни один рецепт БД не остаётся без ingredientIds (было 23/1017)', () => {
    const noIds = RECIPE_DB.filter(r => !r.ingredientIds || r.ingredientIds.length === 0);
    expect(noIds.map(r => r.name), `рецепты без декомпозиции: ${noIds.length}`).toEqual([]);
  });

  it('все ingredientIds существуют в FOOD_DB, у каждого id есть порция > 0', () => {
    const bad: string[] = [];
    for (const r of RECIPE_DB) {
      for (const fid of r.ingredientIds || []) {
        if (!FOOD_IDS.has(fid)) bad.push(`${r.name}: ${fid}`);
      }
      for (const fid of r.ingredientIds || []) {
        const g = r.portions?.[fid];
        if (typeof g !== 'number' || g <= 0) bad.push(`${r.name}: порция ${fid} = ${g}`);
      }
    }
    expect(bad.slice(0, 20), bad.slice(0, 20).join('\n')).toEqual([]);
  });

  it('порции авторских блюд — кулинарные (≥2 г, сумма ≤1000 г на блюдо)', () => {
    const bad: string[] = [];
    for (const r of RECIPE_DB) {
      const parts = Object.values(r.portions || {}) as number[];
      if (parts.some(g => g < 2)) bad.push(`${r.name}: порция ${Math.min(...parts)} г`);
      const sum = parts.reduce((s, g) => s + g, 0);
      // Масс-блюда (BB-Масса) для 110–120 кг легально доходят до ~990 г — это их
      // содержание, а не «свалка». Потолок ловит только явно сломанные суммы.
      if (sum > 1000) bad.push(`${r.name}: сумма ${sum} г`);
    }
    expect(bad.slice(0, 20), bad.slice(0, 20).join('\n')).toEqual([]);
  });

  it('шапка = разбор: kcal рецепта выводится из формулой-согласованных макросов', () => {
    // Кампания зафиксирована синком шапки с декомпозицией — расхождение шапки
    // и разбора у новых раскладок допустимо только округлением малых макросов.
    const small = RECIPE_DB.filter(r => (r.ingredientIds || []).length > 0 && r.kcal > 0)
      .filter(r => {
        const p = r.protein || 0, f = r.fat || 0, c = r.carbs || 0;
        const formula = 4 * p + 4 * c + 9 * f;
        return Math.abs(r.kcal - formula) / r.kcal * 100 > 3;
      });
    expect(small.map(r => `${r.name}: kcal ${r.kcal} vs formula ${Math.round(4 * (r.protein || 0) + 4 * (r.carbs || 0) + 9 * (r.fat || 0))}`)).toEqual([]);
  });
});
