/**
 * Calc.lab-coverage.ts — честная карта «поле заполнено, но расчёт его не читает».
 *
 * Проход 140: форма собирает 88 полей бланка (проход 196 добавил ретикулоциты —
 * 89, проход 203 — СКФ и цистатин C, 91; проход 205 — ЩФ, 92; проход 206 —
 * HbA1c, 93), а модель читает меньше. Молчать об этом нельзя по двум причинам:
 *  - заполненное поле выглядит учтённым: «нет записи» и «записано, но не
 *    прочитано» на экране неотличимы;
 *  - «нет шкалы» ≠ «в норме»: у этих полей нет ни шкалы ступеней, ни правила
 *    советов, ни вклада в риск, ни вывода в анкету, поэтому приложение не имеет
 *    права делать вид, что оценило значение.
 *
 * Список — не мнение, а измерение. Гард `lab-coverage-honest` перебирает все поля
 * `FULL_PANELS` и требует, чтобы каждое либо меняло хотя бы один контур
 * (риск-модель, мост механизмов, ступени/советы, справочная граница ступеней,
 * авто-вывод анкеты), либо было перечислено здесь. Как только поле начинают
 * читать — гард падает и требует убрать его из таблицы.
 *
 * Проход 141: у той же честности есть вторая половина — поле читается, человек в
 * него вписал, а числа из записи не вышло («повышен», «1+», «1 000» до исправления
 * правила чтения). Такие записи называет `labUnreadNotes`.
 */
import type { LabSlice } from '../../../engines/support-plan';
import { labFieldNumber, labFieldUnreadReason } from '../../../engines/support-plan';

