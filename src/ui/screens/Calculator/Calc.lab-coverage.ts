export interface UnusedLabField {
  /** `панель|подпись поля` — тот же ключ, что в таблице. */
  key: string;
  panel: string;
  marker: string;
  reason: string;
}

/**
 * Заполненные поля, которые расчёт не читает. Пустые поля не называем: «не
 * заполнено» и «заполнено, но не читается» — разные вещи, и вторая требует
 * действия (не полагаться на эту строку в советах).
 */
export function unusedLabFields(slice?: LabSlice | null): UnusedLabField[] {
  if (!slice) return [];
  const out: UnusedLabField[] = [];
  for (const [key, reason] of Object.entries(LAB_FIELD_UNUSED_REASON)) {
    const [panel, marker] = key.split('|');
    const val = (slice as any)?.[panel]?.[marker];
    if (val === undefined || val === null || String(val).trim() === '') continue;
    out.push({ key, panel, marker, reason });
  }
  return out;
}
