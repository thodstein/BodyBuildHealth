  // Проход 207: альбумин/креатинин мочи — мг/г.
  'mg/g': 'мг/г',
  'u/l': 'Ед/л', 'u/ml': 'Ед/мл', 'iu/ml': 'МЕ/мл', 'miu/l': 'мМЕ/л',
  // Проход 196: промилле — единица ретикулоцитов в бланке ИНВИТРО. Без русского
  // написания подсказка печатала «‰» как есть, а рядом стоял выбор «%»/«‰».
  '%': '%', '‰': '‰', 'sec': 'сек', '10^9/l': '10⁹/л', '10^12/l': '10¹²/л',
  '10^9/л': '10⁹/л', '10^12/л': '10¹²/л', 'ед/л': 'Ед/л',
