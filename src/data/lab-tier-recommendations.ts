// ════════════════════════════════════════════════════════════════════════════
//  femaleHormoneAlert — тревожные бэнды женских гормонов (проход 83)
// ════════════════════════════════════════════════════════════════════════════
/**
 * Женские гормоны не проходят мужскую лестницу действий (`MALE_ONLY_TIER` в
 * `lab-tier-ranges`), но и молчать о по-настоящему высоких значениях нельзя.
 * Здесь только те пороги, где действие очевидно и не зависит от фазы:
 * E2 >800 и <30, прогестерон >30, пролактин >1500 мМЕ/л, тестостерон >6 нмоль/л.
 * Фазовые коридоры (ЛГ, ФСГ, лютеиновая E2 450) — не повод для алерта: их
 * показывает строка результата своей фазовой нормой.
 *
 * Проход 148: пролактин и тестостерон переводятся в единицы калькулятора
 * (`FEMALE_HORMONE_ULN_READ`): форма читает пролактин в нг/мл (порог 70.8), а
 * тестостерон в нг/дл (порог 173). Раньше бэнд сравнивал 80 нг/мл с 1500 мМЕ/л
 * (молчал всегда) и 50 нг/дл с 6 нмоль/л (кричал у каждой женщины), а `PROLACTIN`
 * из формы не находил ветку `PRL` вовсе.
 */
function femaleHormoneAlert(marker: string, value: number): TierAlert | null {
  const out = (tier: Tier, message: string): TierAlert => ({ marker, value, tier, message });
  switch (marker.toUpperCase()) {
    case 'E2':
    case 'ESTRADIOL':
      if (value > FEMALE_HORMONE_ULN.E2.criticalHigh) {
        return out(3, `⛔ Эстрадиол = ${value} пг/мл — очень высоко для женщины. Не подавлять ИА «на всякий случай»: гинеколог/эндокринолог, проверить фазу и УЗИ яичников.`);
      }
      if (value < FEMALE_HORMONE_ULN.E2.low) {
        return out(2, `Эстрадиол = ${value} пг/мл — ниже 30: дефицит эстрогенов (кости, либидо). Проверить день цикла и обсудить с гинекологом.`);
      }
      return null;
    case 'PROG':
    case 'PROGESTERONE':
      if (value > FEMALE_HORMONE_ULN.PROG.criticalHigh) {
        return out(2, `Прогестерон = ${value} нг/мл — выше лютеинового коридора (5–20): 19-нор, беременность или киста жёлтого тела — гинеколог.`);
      }
      return null;
    case 'PRL':
    case 'PROLACTIN':
      if (value > FEMALE_HORMONE_ULN_READ.PRL.criticalHigh) {
        return out(3, `Пролактин = ${value} нг/мл — очень высоко для женщины (порог ${FEMALE_HORMONE_ULN_READ.PRL.criticalHigh}): исключить пролактиному (макропролактин, МРТ) — эндокринолог.`);
      }
      return null;
    case 'TESTOSTERONE':
    case 'TOTAL_T':
    case 'TT':
      if (value > FEMALE_HORMONE_ULN_READ.TT.criticalHigh) {
        return out(2, `Тестостерон = ${value} нг/дл — выше женской нормы 0.3–2.5 нмоль/л (порог ${FEMALE_HORMONE_ULN_READ.TT.criticalHigh} нг/дл). Вирилизация (голос, клитор, акне): гинеколог-эндокринолог.`);
      }
      return null;
    default:
      return null;
  }
}

// ════════════════════════════════════════════════════════════════════════════
//  femaleHormoneSteps — женская лестница действий (проход 97)
// ════════════════════════════════════════════════════════════════════════════
/**
 * Мужская лестница (`TIER_RULES`) женщине не применяется: `MALE_ONLY_TIER` даёт
 * ступень 0, и без этого блока она на «пограничном» гормоне не получала ничего —
 * алерт есть только у крайних бэндов (>800 E2, >1500 PRL, >30 PROG, >6 TT).
 * Пограничная полоса (выше коридора, но не тревожно) оставалась пустой, хотя
 * именно там и нужен следующий шаг — и он диагностический, а не лечебный: одно
 * значение гормона без дня цикла не лечат, его перепроверяют.
 *
 * Пороги — `FEMALE_HORMONE_ULN` (те же числа, что у бэндов и у `interpretLabs`):
 * E2 «>400» и «<30», прогестерон «>20», пролактин «>800», тестостерон «>2.5».
 * Шаги — 1 = пересдать в правильную фазу, 2 = визуализация/смежный анализ.
 *
 * Проход 148: пролактин и тестостерон сравниваются в единицах калькулятора
 * (`FEMALE_HORMONE_ULN_READ`: нг/мл и нг/дл) — иначе порог 800 против 80 нг/мл
 * молчал, а 2.5 против 50 нг/дл срабатывал у всех.
 */
function femaleHormoneSteps(marker: string, value: number): TierNutritionTip[] {
  const out: TierNutritionTip[] = [];
  const tip = (tier: Tier, action: string, target: string) => out.push({ action, target, marker, tier });
  switch (marker.toUpperCase()) {
    case 'E2':
    case 'ESTRADIOL': {
      const u = FEMALE_HORMONE_ULN.E2;
      if (value < u.low) {
        tip(1, 'Пересдать E2', 'в фолликулярную фазу, вместе с ФСГ и АМГ');
      } else if (value > u.high) {
        tip(1, 'Пересдать E2', '2–5 день цикла, без стимуляции овуляции');
        tip(2, 'УЗИ', 'яичники и фолликулогенез — исключить кисту и гиперстимуляцию');
      }
      break;
    }
    case 'PROG':
    case 'PROGESTERONE': {
      if (value > FEMALE_HORMONE_ULN.PROG.high) {
        tip(1, 'Пересдать прогестерон', 'за 7 дней до менструации (лютеиновая фаза)');
        tip(2, 'УЗИ', 'жёлтое тело и кисты — гинеколог');
      }
      break;
    }
    case 'PRL':
    case 'PROLACTIN': {
      if (value > FEMALE_HORMONE_ULN_READ.PRL.high) {
        tip(1, 'Повторить пролактин', 'утром натощак, без физнагрузки и стресса за сутки');
        tip(2, 'ТТГ и макропролактин', 'исключить гипотиреоз и макропролактин');
      }
      break;
    }
    case 'TESTOSTERONE':
    case 'TOTAL_T':
    case 'TT': {
      if (value > FEMALE_HORMONE_ULN_READ.TT.high) {
        tip(1, 'Повторить тестостерон', 'утро, 8–10 день цикла, вместе с ГСПГ');
        tip(2, 'Гинеколог-эндокринолог', 'оценка вирилизации: голос, кожа, цикл');
      }
      break;
    }
    default:
      break;
  }
  return out;
}

// ════════════════════════════════════════════════════════════════════════════
//  computeTierAdjustments — главная функция
// ════════════════════════════════════════════════════════════════════════════
export function computeTierAdjustments(labs: Record<string, number>, sex?: 'male' | 'female'): TierAdjustmentResult {
  const addSubs: TierAddSub[] = [];
  const titrations: TierTitration[] = [];
  const nutrition: TierNutritionTip[] = [];
  const alerts: TierAlert[] = [];
  const tierSummary: { marker: string; value: number; tier: Tier; label: string; unit: string }[] = [];
  let stopCourse = false;

  for (const [marker, value] of Object.entries(labs)) {
    if (typeof value !== 'number' || isNaN(value)) continue;

    // Проход 136: имя анализа переводится в словарь лестниц одной таблицей
    // (`tierMarkerKey`), иначе `HEMATOCRIT`/`TOTAL_CHOLESTEROL`/`PROTEIN` (моча)/
    // `ANTI_TPO`/`IL_6` из формы не находили ни шкалы, ни действий. Если в карте
    // есть и каноническое имя — считаем его, а псевдоним пропускаем, чтобы одна
    // находка не задвоилась.
    const ruleKey = tierMarkerKey(marker);
    // Проход 175: у второго написания своего правила может не быть (в `TIER_RULES`
    // `HEMOGLOBIN`, `E2`, `PRL`, `TESTOSTERONE`; ступень при этом считалась и под
    // `HGB`, `ESTRADIOL`, `PROLACTIN`, `TOTAL_T`) — совет молча пропадал.
    const same = TIER_SAME_ANALYSIS[ruleKey];
    const sameKey = same?.canon;
    if (ruleKey !== marker.toUpperCase() && labs[ruleKey] !== undefined) continue;
    // Одна карта с двумя написаниями одного анализа — считаем каноническое имя.
    // ВчСРБ — исключение (`distinct`): он идёт отдельной находкой рядом с СРБ.
    if (sameKey && !same?.distinct && labs[sameKey] !== undefined) continue;

    // Проход 83: женские гормоны идут своим путём. `deriveTier` для них вернёт 0
    // (мужская лестница не применяется), поэтому тревожные бэнды женской модели
    // печатаем здесь — своей формулировкой, без анастрозола и кломифена.
    // Проход 97: плюс своя лестница шагов (`femaleHormoneSteps`) — диагностика
    // вместо мужских действий, чтобы пограничный гормон не оставался без
    // следующего шага.
    if (sex === 'female') {
      const femAlert = femaleHormoneAlert(marker, value);
      const femSteps = femaleHormoneSteps(marker, value);
      if (femAlert) alerts.push(femAlert);
      for (const s of femSteps) nutrition.push(s);
      if (femAlert || femSteps.length > 0) {
        tierSummary.push({
          marker,
          value,
          tier: femAlert ? femAlert.tier : (Math.max(...femSteps.map(s => s.tier)) as Tier),
          label: '',
          unit: '',
        });
      }
    }

    const tier = deriveTier(marker, value, sex);
    if (tier === 0) continue;

    const rule = TIER_RULES.find(r => r.marker === ruleKey)
      ?? (sameKey ? TIER_RULES.find(r => r.marker === sameKey) : undefined);
    if (!rule) continue;

    tierSummary.push({
      marker,
      value,
      tier,
      label: '', // заполнить из LAB_TIERS если нужно
      unit: '',
    });

    // CRITICAL: калий/натрий — direction:'both'. Добавлять препарат/соль ТОЛЬКО при НИЗКОЙ стороне.
    // При ВЫСОКОЙ стороне (гиперкалиемия/гипернатриемия) добавка K⁺/соли — фатальна → ограничение.
    const mkey = ruleKey;
    const tdef = LAB_TIERS[mkey];
    const isHighSide = !!tdef && tdef.direction === 'both' && value > (tdef.normal[0] + tdef.normal[1]) / 2;
    if ((mkey === 'POTASSIUM' || mkey === 'SODIUM') && isHighSide && tier > 0 && tier < 3) {
      nutrition.push({
        action: mkey === 'POTASSIUM' ? '🛑 ОГРАНИЧИТЬ КАЛИЙ' : '🛑 ОГРАНИЧИТЬ НАТРИЙ',
        target: mkey === 'POTASSIUM'
          ? 'Исключить бананы/авокадо/картофель/апельсины/шпинат; диуретик (фуросемид/буметанид) по врачу; ЭКГ (риск аритмии)'
          : 'Снизить соль <3 г/день; контроль АД и водного баланса; врач (риск отёка мозга/сердца)',
        marker,
        tier,
      });
      continue;
    }

    // Проход 141: шаг правила выбирается по стороне двусторонней шкалы. Основное
    // содержание — для стороны, для которой правило писалось; `low`/`high` — явное
    // исключение для другой стороны. Нет исключения — всё как раньше, поэтому
    // односторонние шкалы (печень, липиды, витамины) не меняются.
    const lowSide = !!tdef && (tdef.direction === 'low' || (tdef.direction === 'both' && !isHighSide));
    const stepFor = (step: TierStepContent | undefined): TierStepContent | undefined => {
      if (!step) return undefined;
      const alt = lowSide ? step.low : step.high;
      return alt ?? step;
    };

    const step1 = stepFor(rule.tier1);
    if (tier === 1 && step1) {
      if (step1.add) {
        for (const [id, reason, dose] of step1.add) {
          addSubs.push({ id, reason, dose, tier, marker });
        }
      }
      if (step1.titrate) {
        for (const [id, factor, reason] of step1.titrate) {
          titrations.push({ id, factor, reason, tier, marker });
        }
      }
      if (step1.nutrition) {
        for (const [action, target] of step1.nutrition) {
          nutrition.push({ action, target, marker, tier });
        }
      }
    }

    const step2 = stepFor(rule.tier2);
    if (tier === 2 && step2) {
      if (step2.add) {
        for (const [id, reason, dose] of step2.add) {
          addSubs.push({ id, reason, dose, tier, marker });
        }
      }
      if (step2.titrate) {
        for (const [id, factor, reason] of step2.titrate) {
          titrations.push({ id, factor, reason, tier, marker });
        }
      }
      if (step2.nutrition) {
        for (const [action, target] of step2.nutrition) {
          nutrition.push({ action, target, marker, tier });
        }
      }
    }

    const step3 = stepFor(rule.tier3);
    if (tier === 3 && step3) {
      for (const alertTemplate of step3.alerts ?? []) {
        const message = alertTemplate.replace('{value}', String(value));
        alerts.push({ marker, value, tier, message, stopCourse: step3.stopCourse ?? false });
      }
      if (step3.stopCourse) stopCourse = true;
      if (step3.nutrition) {
        for (const [action, target] of step3.nutrition) {
          nutrition.push({ action, target, marker, tier });
        }
      }
    }
  }

  return { addSubs, titrations, nutrition, alerts, stopCourse, tierSummary };
}

