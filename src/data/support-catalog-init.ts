// ════════════════════════════════════════════════════════════════════
//  support-catalog-init.ts — ЕДИНАЯ точка инициализации каталога поддержки.
//
//  Проблема (C6, audit): registerCatalogExtras мутировал каталог как
//  сайд-эффект импорта UI-компонентов Калькулятора (Calc.mapper.tsx и др.),
//  а хаб «6 в 1» тот же каталог не регистрировал ⇒ видимое содержимое
//  каталога зависело от порядка монтирования компонентов.
//
//  Решение: детерминированный порядок сборки в одном месте:
//    1) базовые записи — support-catalog-data;
//    2) ручные богатые записи шарда — support-catalog-supplement
//       (дописывает ТОЛЬКО отсутствующие ключи, поэтому обязан идти
//       ДО автогенератора — иначе автозаписи вытеснят богатые);
//    3) автогенератор для всех оставшихся мех-веществ —
//       registerCatalogExtras (идемпотентный).
//
//  Импорт этого модуля где угодно даёт одинаковый полный каталог.
//  Прямой импорт support-catalog-data без этого модуля остаётся
//  ЧАСТИЧНЫМ (контракт: полный каталог — только через init).
// ════════════════════════════════════════════════════════════════════

import { SUPPORT_CATALOG_DATA } from './support-catalog-data';
import './support-catalog-supplement';
import { registerCatalogExtras } from './support-catalog-extras';

let _done = false;

/** Идемпотентная инициализация полного каталога поддержки. */
export function initSupportCatalog(): void {
  if (_done) return;
  _done = true;
  registerCatalogExtras(SUPPORT_CATALOG_DATA);
}

// Авто-инициализация при импорте: любой потребитель полного каталога
// получает одинаковое состояние без ручных вызовов.
initSupportCatalog();
