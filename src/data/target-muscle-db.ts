/**
 * Профессиональная база данных ЦЕЛЕВЫХ МЫШЦ (Target Muscle DB).
 *
 * Источник: анатомия, биомеханика, практический опыт профессионального бодибилдинга.
 * Каждая запись — ДЕТАЛЬНОЕ описание региона/головки мышцы с инструкцией
 * по нейромышечной связи (mind-muscle connection) и оптимизации техники.
 *
 * Структура:
 *  - muscleKey: уникальный ключ целевого региона (напр. 'pec_upper', 'quad_lateralis')
 *  - nameRu: русское название региона
 *  - anatomy: анатомическая справка (происхождение, прикрепление, иннервация)
 *  - fiberDominance: преобладающий тип волокон (fast/slow/mixed)
 *  - function: биомеханическая функция (сокращённо)
 *  - mmc: mind-muscle connection — как «почувствовать» мышцу
 *  - techniqueCues: профессиональные подсказки по технике под эту мышцу
 *  - stretchKey: нужно ли растяжение (да/нет) и как
 *  - peakKey: нужно ли пиковое сокращение и где
 *  - tempoRecommendation: рекомендованный темп (ecc-bot-con-top)
 *  - volumeRecommendation: рекомендации по объёму (сеты/нед)
 *  - commonMistakes: типичные ошибки именно для этой мышцы
 *  - regionalEmphasis: как сместить акцент внутри группы
 *  - exerciseMask: какие id упражнений попадают под эту мышцу
 *
 * @module target-muscle-db
 */

