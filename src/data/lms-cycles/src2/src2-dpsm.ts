import type { SRCycleTemplate, SRDaySpec, SRSetSpec, SRExerciseSpec } from '../lms-types';

// Компактные хелперы (данные, не логика).
const s = (pct: number, reps: number, sets = 1): SRSetSpec => ({ pct, reps, sets });
const ex = (name: string, group: string, coef: number, sets: SRSetSpec[]): SRExerciseSpec => ({ name, group, coef, mnosz: 1, sets });
const day = (...exercises: SRExerciseSpec[]): SRDaySpec => ({ exercises });

const BP = (sets: SRSetSpec[]) => ex('Жим лёжа', 'Жим', 1.0, sets);
const DL = (sets: SRSetSpec[]) => ex('Становая тяга', 'Тяга', 1.0, sets);

// Полноценная ПЛ-структура: тяга + спина + пресс после основного жима
const dlM = DL([s(.35,5), s(.50,4), s(.65,2), s(.55,5,3)]);
const row = ex('Тяга штанги в наклоне', 'Спина', 0.5, [s(.50,8,3)]);
const abs = ex('Пресс', 'Пресс', 0, [s(.15,15,3)]);

// ДПСМ (Суровецкий), лист «Лист1». Опорный ПМ источника = 125 (pct = вес_строки / 125).
// Жимовая специализация: 16 тренировок = 4 микроцикла × 4 сессии.
// Между микроциклами перерыв не менее 3-х дней (граница микроцикла = граница недели).
// Каждый микроцикл — 4 типа сессии:
//   1) динамика (доводящая 4×3),
//   2) жим с паузой 3 сек,
//   3) скоростная (10×3, отдых между подходами <30 сек),
//   4) выход на максимум (4-3-2-1).
// МК1/МК2 — базовые веса; МК3 (+5 кг к рабочим) и МК4 (+2.5 кг) — расширенная сетка процентов.
const weeks: SRDaySpec[][] = [
 // МК1 (т1-т4)
 [
  // т1 — динамика (85% / 4×3)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.75, 4), s(.85, 4, 3)]), dlM, row, abs),
  // т2 — жим с паузой 3 сек (75% / 4×3)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.75, 4, 3)]), dlM, row, abs),
  // т3 — скоростная (65% / 10×3, отдых <30 сек)
  day(BP([s(.36, 8), s(.54, 6), s(.65, 10, 3)]), dlM, row, abs),
  // т4 — выход на максимум (4-3-2-1)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.75, 4), s(.85, 3), s(.92, 2), s(1.00, 1)]), dlM, row, abs),
 ],
 // МК2 (т5-т8)
 [
  // т5 — динамика (84% / 4×3)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.74, 4), s(.84, 4, 3)]), dlM, row, abs),
  // т6 — жим с паузой 3 сек (74% / 4×3)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.74, 4, 3)]), dlM, row, abs),
  // т7 — скоростная (66% / 10×3, отдых <30 сек)
  day(BP([s(.36, 8), s(.54, 6), s(.66, 10, 3)]), dlM, row, abs),
  // т8 — выход на максимум (4-3-2-1)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.74, 4), s(.84, 3), s(.92, 2), s(1.00, 1)]), dlM, row, abs),
 ],
 // МК3 (т9-т12, +5 кг к рабочим весам, расширенная сетка)
 [
  // т9 — динамика (88% / 4×3)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.78, 4), s(.88, 4, 3)]), dlM, row, abs),
  // т10 — жим с паузой 3 сек (78% / 4×3)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.78, 4, 3)]), dlM, row, abs),
  // т11 — скоростная (68% / 10×3, отдых <30 сек)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 10, 3)]), dlM, row, abs),
  // т12 — выход на максимум (4-3-2-1)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.76, 4), s(.84, 3), s(.92, 2), s(1.00, 1)]), dlM, row, abs),
 ],
 // МК4 (т13-т16, +2.5 кг к рабочим весам, объёмный акцент 6×3)
 [
  // т13 — динамика (88% / 6×3)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.78, 4), s(.88, 6, 3)]), dlM, row, abs),
  // т14 — жим с паузой 3 сек (78% / 6×3)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.78, 6, 3)]), dlM, row, abs),
  // т15 — скоростная (70% / 10×3, отдых <30 сек)
  day(BP([s(.36, 8), s(.54, 6), s(.70, 10, 3)]), dlM, row, abs),
  // т16 — выход на максимум (4-3-2-1)
  day(BP([s(.36, 8), s(.54, 6), s(.68, 5), s(.76, 4), s(.84, 3), s(.92, 2), s(1.00, 1)]), dlM, row, abs),
 ],
];

