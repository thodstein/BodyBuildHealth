/** Resolve a template exercise name to a catalog ID. */
export function resolveCatalogId(templateName: string): string | null {
  const n = (templateName || '').toLowerCase().replace(/ё/g, 'е').trim();
  return EXERCISE_ALIAS_MAP[n] ?? null;
}
