/**
 * POTASSIUM_ACTION — три «верхних» числа калия: это не одна норма, а три разных
 * вопроса к одному анализу. Они сведены в один именованный реестр, чтобы все три
 * жили в одном месте; ни одно число не выведено из другого.
 *
 * - `reportFlagHigh` = 5.5 — флаг текста комплексного отчёта
 *   (`comprehensive-report.engine`: «Калий … — гиперкалиемия! Риск аритмии»).
 *   Это флаг рекомендации, а не ступень действия: он печатает текст, как только
 *   калий заметно выше верхней границы нормы 5.1. Первичного guideline-источника
 *   у самого 5.5 нет — порог приложения.
 * - `criticalResultHigh` = 6.0 — «критический» результат разбора анализов
 *   (`lab-analysis.engine`, `REFERENCE_RANGES.POTASSIUM.criticalHigh`).
 *   Порог приложения, первичного источника нет: за guideline не выдаётся.
 * - `emergencyHigh` = 6.5 — неотложная граница ступени (`LAB_TIERS.POTASSIUM`):
 *   тяжёлой дискалиемией считаются K < 2.5 или > 6.5 ммоль/л (PMID 30353786),
 *   внутривенный кальций показан при K ≥ 6.5 (PMID 41506858).
 *
 * Почему нельзя «выровнять» до одного числа: вопросы разные — флаг отчёта /
 * критический результат разбора / неотложная помощь. Общее число меняет вердикт
 * хотя бы на одной поверхности: 5.5 в `LAB_TIERS` объявляло бы экстренной обычную
 * гиперкалиемию, а 6.5 в отчёте молчало бы о риске аритмии там, где текст уже
 * нужен. Поэтому тройка записана и объяснена в
 * `docs/LAB-NORMS-SINGLE-SOURCE.md` §4, а не «поправлена» молча.
 */
export const POTASSIUM_ACTION = {
  reportFlagHigh: 5.5,
  criticalResultHigh: 6.0,
  emergencyHigh: 6.5,
} as const;
