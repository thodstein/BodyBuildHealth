/**
 * lab-storage-code.ts — проход 179: одно написание кода анализа в складе.
 *
 * Чтение анализа давно терпимо к написанию: `ucumInfo` ищет запись каталога без
 * учёта регистра (проход 174), мост `canonicalLabValues` добавляет канон-ключи
 * (169), `findLabPoint` знает алиасы (86). А запись — нет: ручной ввод писал
 * `inputCode.toUpperCase()` (`hba1c` → `HBA1C`), OCR после `mapToUcumCode` писал
 * `HbA1c`, парсер бланка мог дать `CKMB`, а `LAB_TIERS`/`LAB_REF` спрашивают
 * `CK_MB`. Один анализ ложился двумя записями — история делилась на два ряда,
 * «просрочен»/дедупликация/тренд видели половину точек.
 *
 * Правило записи — то же, что у OCR и каталога: `mapToUcumCode` (алиас → ключ
 * `UCUM_MAP`, иначе код как есть). Своей таблицы имён здесь нет намеренно:
 * вторая таблица неизбежно разошлась бы с первой.
 *
 * Приводится только код (`code`); `name` остаётся подписью, которую прочитали
 * из бланка. Неизвестный код не выбрасывается и не подменяется: он остаётся
 * как ввели (обрезанный по краям), иначе анализ без записи в каталоге потерял
 * бы имя, под которым его вводили.
 */
import { mapToUcumCode } from './labs-mapping';

/** Код анализа в написании склада (вызывается на границе записи, а не в UI). */
export function labStorageCode(code: string | null | undefined): string {
  const raw = String(code ?? '').trim();
  if (!raw) return raw;
  return mapToUcumCode(raw);
}
