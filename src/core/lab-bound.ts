/**
 * lab-bound.ts — что можно утверждать, если в бланке стоит граница.
 *
 * Проход 138: бланк печатает «Ферритин >1000 нг/мл», когда результат за
 * пределами линейного диапазона метода. Число в расчёт идёт как есть (иначе
 * шкала ступеней не работает), но «>1000» значит «не меньше 1000», а «<0.5» —
 * «не больше 0.5», поэтому вывод о стороне отклонения нельзя делать, если
 * граница его не доказывает: «>1000» при нижней границе 30 не делает результат
 * низким, а «<0.5» при верхней границе 3 — высоким.
 *
 * Проход 142: то же правило понадобилось там, где раньше вывод делался всегда —
 * дневник анализов («в норме» по обрезанному числу), HL7-выгрузка (флаг
 * отклонения), повторное сохранение панели (знак терялся вместе с записью).
 * Один модуль — одно толкование знака, чтобы импорт, дневник и выгрузка не
 * спорили друг с другом.
 *
 * Проход 144: сюда же переехало «можно ли печатать разность» — «>800 → >1000»
 * это не «+200», поэтому ни стрелка, ни процент по обрезанным числам не
 * считаются (экраны «было → стало»).
 */

/** Знак границы, как он напечатан в бланке. */
export type LabBound = '<' | '>';

/**
 * Сторона отклонения, которую запись доказывает.
 *
 * Число без границы доказано целиком: 500 при верхней границе 400 — высокое.
 * С границей доказана только одна сторона:
 *  - «>N» — значение больше N, значит при N ≥ верхней границы оно точно высокое,
 *    а «ниже нормы» доказать нельзя (значение может быть и в норме);
 *  - «<N» — зеркально: N ≤ нижней границы доказывает «низкое».
 *
 * Сравнение нестрогое (`>=`/`<=`): «>400» при верхней границе 400 — это уже
 * выше нормы, «<30» при нижней 30 — уже ниже.
 *
 * @returns `'high'` / `'low'` — доказано; `undefined` — запись не позволяет судить.
 */
export function boundProvesSide(
  bound: LabBound | undefined,
  value: number,
  low: number | undefined,
  high: number | undefined,
): 'high' | 'low' | undefined {
  if (!Number.isFinite(value)) return undefined;
  if (bound === '>') {
    return high !== undefined && value >= high ? 'high' : undefined;
  }
  if (bound === '<') {
    return low !== undefined && value <= low ? 'low' : undefined;
  }
  if (high !== undefined && value > high) return 'high';
  if (low !== undefined && value < low) return 'low';
  return undefined;
}

/**
 * Что можно утверждать про отклонение, если в бланке стоит граница.
 *
 * «>1000» значит «не меньше 1000»: заключение «ниже нормы» доказать нельзя —
 * значение может быть и выше. «<0.5» зеркально: нельзя утверждать «выше нормы».
 * Обратные выводы остаются: «>1000» при верхней границе 400 — точно высокое,
 * «<0.5» при нижней границе 3 — точно низкое.
 */
export function boundMakesConclusionUnsafe(
  bound: '<' | '>' | undefined,
  value: number,
  low: number | undefined,
  high: number | undefined,
): boolean {
  if (!bound) return false;
  const belowLow = low !== undefined && value < low;
  const aboveHigh = high !== undefined && value > high;
  return bound === '>' ? belowLow : aboveHigh;
}

/**
 * Знак границы переживает повторное сохранение, если число не изменили.
 *
 * Проход 142: расширенная панель и каталог анализов при сохранении заново
 * пишут в склад новую запись из числа в поле. «>1000» в поле становится 1000,
 * и знак исчезал — запись выглядела точным измерением. Если человек число не
 * менял, знак принадлежит тому же результату и его надо вернуть.
 */
export function keptBound(
  existing: { value: number; bound?: LabBound } | undefined,
  value: number,
): LabBound | undefined {
  if (!existing?.bound) return undefined;
  return Math.abs(existing.value - value) < 1e-9 ? existing.bound : undefined;
}

/**
 * Можно ли печатать разность двух записей.
 *
 * Проход 144: разность доказывается только у двух точных чисел. «>800 → >1000»
 * значит «стало не меньше 1000», а не «+200»: нижняя граница прошлой записи
 * ничего не говорит о её истинном значении. Одна граница с любой стороны — уже
 * не разность, а неизвестность.
 */
export function boundsComparable(a?: LabBound, b?: LabBound): boolean {
  return !a && !b;
}

/**
 * Направление изменения, которое доказывают две записи с границами.
 *
 * Проход 156: динамика калькулятора сравнивала числа, стоящие за границей, как
 * точные измерения — «>1000 → 2000» называлось «ухудшением», хотя «>1000» может
 * быть и 5000. Запись здесь — интервал: «>N» — `[N, +∞)`, «<N» — `(−∞, N]`,
 * точное число — точка. Направление доказано, только если интервалы не
 * пересекаются:
 *  - «>1000 → 300» — вниз (прошлое больше 1000, нынешнее ровно 300);
 *  - «<0.5 → 3» — вверх (прошлое меньше 0.5, нынешнее ровно 3);
 *  - «>1000 → 2000» — ничего: прошлое может быть и 2000, и 100000.
 *
 * @returns `'up'` / `'down'` — доказано; `undefined` — записи не позволяют судить.
 */
export function boundsOrder(
  a: { value: number; bound?: LabBound },
  b: { value: number; bound?: LabBound },
): 'up' | 'down' | undefined {
  // Интервал записи: граница «>» тянется вверх, «<» — вниз, точное число — точка.
  const lo = (x: { value: number; bound?: LabBound }) =>
    x.bound === '>' ? x.value : x.bound === '<' ? -Infinity : x.value;
  const hi = (x: { value: number; bound?: LabBound }) =>
    x.bound === '<' ? x.value : x.bound === '>' ? Infinity : x.value;

  if (!a.bound && !b.bound) {
    if (b.value > a.value) return 'up';
    if (b.value < a.value) return 'down';
    return undefined;
  }
  if (hi(a) <= lo(b)) return 'up';
  if (hi(b) <= lo(a)) return 'down';
  return undefined;
}

/**
 * Направление и процент изменения между двумя записями — для экранов
 * («было → стало»).
 *
 * При границе не печатается ни стрелка, ни процент: сторона и величина не
 * доказаны. Нулевое прошлое значение процента не даёт (делить не на что), но
 * направление остаётся.
 */
export function labDelta(
  existing: { value: number; bound?: LabBound },
  next: { value: number; bound?: LabBound },
): { arrow: '↑' | '↓' | '→' | ''; pct: number | null } {
  if (!boundsComparable(existing.bound, next.bound)) return { arrow: '', pct: null };
  const delta = next.value - existing.value;
  const pct = existing.value !== 0 ? Math.round((delta / Math.abs(existing.value)) * 100) : null;
  return { arrow: delta > 0 ? '↑' : delta < 0 ? '↓' : '→', pct };
}
