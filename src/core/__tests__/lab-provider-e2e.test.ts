describe('сквозной разбор бланков Гемотест / Хеликс / Инвитро / КДЛ', () => {
  for (const [provider, text] of Object.entries(PROVIDERS)) {
    it(`${provider}: показатели извлекаются с корректными значениями`, async () => {
      const res = await processUploadedFile(file(text, `${provider}.txt`));
      const byCode = new Map(res.labs.map((l) => [l.code, l]));

      expect(res.labs.length).toBeGreaterThanOrEqual(12);
      expect(byCode.get('ALT')?.value).toBeGreaterThan(0);
      expect(byCode.get('AST')?.value).toBeGreaterThan(0);
      expect(byCode.get('CREATININE')?.unit).toBe('umol/L');
      expect(byCode.get('GLU')?.unit).toBe('mmol/L');

      // Гормоны в «н»/«п» единицах обязаны пересчитаться в канонические.
      const tt = byCode.get('TT');
      expect(tt, 'Тестостерон не найден').toBeDefined();
      expect(tt!.unit).toBe('ng/dL');
      expect(tt!.value).toBeGreaterThan(200);

      // Никаких дублей одного и того же показателя под разными кодами.
      expect(res.labs.filter((l) => l.code === 'CHOL' || l.code === 'Cholesterol_Total').length).toBeLessThanOrEqual(1);
    });
  }
});
