/**
 * data-space-install.ts — ставит шов пространств данных ПЕРВЫМ импортом приложения.
 *
 * Почему отдельным модулем: ES-модули вычисляются в порядке импорта, поэтому
 * `import './core/data-space-install'` первой строкой `main.tsx` гарантирует, что
 * подмена `localStorage` произошла до того, как остальные модули начнут читать
 * данные (иначе старт в пространстве атлета показал бы данные профиля устройства).
 *
 * Если среда не даёт подменить хранилище (или localStorage недоступен), приложение
 * продолжает работать как раньше: изоляция не включается, данные не теряются.
 */
import { installDataSpaceStorage } from './data-space';

try {
  if (typeof window !== 'undefined') installDataSpaceStorage(window);
} catch {
  /* без изоляции, но с рабочим приложением */
}
