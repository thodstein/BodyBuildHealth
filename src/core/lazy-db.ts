/**
 * lazy-db.ts — единственная дверь к базе для экранов, которым она нужна редко.
 *
 * ЗАЧЕМ. `core/db` тянет IndexedDB-обвязку и движки. Экрану профиля он нужен
 * только в трёх редких действиях тренера (посчитать записи, удалить базу,
 * посмотреть список баз). Статический импорт уводил всё это в граф вкладки и
 * замедлял холодный старт телефона.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ `import()` В КОМПОНЕНТЕ. Один шов:
 *  • модуль грузится один раз на процесс (`cached`), а не по одному разу на
 *    каждое место вызова;
 *  • ошибка загрузки не кешируется навсегда — следующий вызов пробует снова
 *    (после обновления приложения в WebView это реальный случай);
 *  • тесты подменяют `core/db` в одном месте, а не гоняются за динамическими
 *    импортами внутри обработчиков.
 */
export type DbModule = typeof import('./db');

let cached: Promise<DbModule> | null = null;

/** Загрузить модуль базы (один раз, лениво). */
export function loadDb(): Promise<DbModule> {
  if (!cached) {
    cached = import('./db').catch(err => {
      cached = null;
      throw err;
    });
  }
  return cached;
}

/** Сброс кеша (нужен тестам). */
export function _resetLazyDb(): void {
  cached = null;
}
