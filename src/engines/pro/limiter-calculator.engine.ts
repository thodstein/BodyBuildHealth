/* ────────────────────────── Резолвер упражнений (СКОБКО-ТОЧНЫЙ) ──────────────────────────
 * Приоритет: полное имя (со скобками) в каталоге → в СРЦ-пуле → без скобок → fuzzy.
 * «Жим в раме (старт)» НЕ должен совпасть с «Жим в раме (дожим)». */

function limiterSearchTokens(name: string): string[] {
  return norm(name.replace(/\(.*?\)/g, ' '))
    .split(/[^a-zа-яё0-9]+/i)
    .filter(t => t.length >= 3 && !/^\d+$/.test(t) && !['сек', 'см', 'мин', 'секунд', 'секунды'].includes(t));
}

function limiterTokenMatch(a: string, b: string): boolean {
  if (a === b) return true;
  const n = Math.min(a.length, b.length, 5);
  if (n < 4) return false;
  return a.slice(0, n) === b.slice(0, n);
}

/** Псевдо-Exercise из записи СРЦ-пула: группа — ПО ИМЕНИ (не по кодам groups). */
function lmsToExercise(lms: { name: string; groups: string[]; coef: number; mnosz: number; uses: number }): Exercise {
  const pool = (Object.keys(PL_WEAK_GROUP_ALLOWED_PATTERNS) as string[]).flatMap(g => getExercisesByGroup(g));
  const catalogMatch = pool.find(e => norm(e.name) === norm(lms.name));
  return {
    id: 'lms_' + norm(lms.name).replace(/[^a-zа-яё0-9]+/gi, '_'),
    name: lms.name,
    group: catalogMatch ? catalogMatch.group : limiterNameGroup(lms.name),
    type: 'compound',
    equipment: 'barbell',
    difficulty: 'intermediate',
    jointStress: 'med',
    fatigueCost: Math.round((lms.coef ?? 1) * 6),
    movementPattern: catalogMatch?.movementPattern,
    targetMuscle: lms.groups.join(', '),
  };
}

/** Пул упражнений: ПЛ-группы каталога + СРЦ-пул + реестр ПЛ-коррекций. */
function limiterPool(): Exercise[] {
  return [
    ...(Object.keys(PL_WEAK_GROUP_ALLOWED_PATTERNS) as string[]).flatMap(g => getExercisesByGroup(g)),
    ...PL_CORRECTION_EXERCISES,
  ];
}

/** Резолв имени в Exercise. Скобко-точный. Возвращает undefined если не найден. */
export function resolveLimiterExercise(name: string): Exercise | undefined {
  const nFull = norm(name);
  const nStripped = norm(name.replace(/\(.*?\)/g, ' '));
  const pool = limiterPool();

  const exactFull = pool.find(e => norm(e.name) === nFull);
  if (exactFull) return exactFull;
  const lmsFull = LMS_EXERCISES.find(l => norm(l.name) === nFull);
  if (lmsFull) return lmsToExercise(lmsFull);

  if (nStripped !== nFull) {
    const exactStripped = pool.find(e => norm(e.name) === nStripped);
    if (exactStripped) return exactStripped;
    const lmsStripped = LMS_EXERCISES.find(l => norm(l.name) === nStripped);
    if (lmsStripped) return lmsToExercise(lmsStripped);
  }

  const tokens = limiterSearchTokens(name);
  if (tokens.length === 0) return undefined;
  let best: Exercise | undefined;
  let bestScore = 0;
  for (const e of pool) {
    const en = norm(e.name);
    const eTokens = limiterSearchTokens(e.name);
    let score = 0;
    for (const t of tokens) {
      if (eTokens.some(et => limiterTokenMatch(et, t))) score += 1;
      else if (t.length >= 5 && en.includes(t)) score += 1;
    }
    if (score >= 2 && score > bestScore) { best = e; bestScore = score; }
  }
  if (best) return best;
  for (const t of tokens) {
    if (t.length >= 5) {
      const hit = pool.find(e => norm(e.name).includes(t));
      if (hit) return hit;
    }
  }
  let bestLms: (typeof LMS_EXERCISES)[number] | undefined;
  let bestLmsScore = 0;
  for (const l of LMS_EXERCISES) {
    const lt = limiterSearchTokens(l.name);
    let score = 0;
    for (const t of tokens) {
      if (lt.some(et => limiterTokenMatch(et, t))) score += 1;
    }
    if (score >= 2 && score > bestLmsScore) { bestLms = l; bestLmsScore = score; }
  }
  if (bestLms) return lmsToExercise(bestLms);
  for (const t of tokens) {
    if (t.length >= 5) {
      const hit = LMS_EXERCISES.find(l => norm(l.name).includes(t));
      if (hit) return lmsToExercise(hit);
    }
  }
  return undefined;
}

/** Паттерн упражнения (для пометки в UI). */
export function limiterPatternOf(exercise: Exercise): string {
  return exercise.movementPattern || derivePattern(exercise);
}

/** Элемент анализа: конкретное упражнение опции с протоколом опции. */
export interface LimiterExerciseItem {
  exercise: Exercise;
  targetGroup: string;
  optimal: boolean;
  rationale: string;
  protocol: LimiterProtocol;
  pattern: string;
}

/** Анализ опции: резолв упражнений в пуле + протокол опции (не из раскладки цикла). */
export function analyzeLimiterOption(option: LimiterOption): { option: LimiterOption; items: LimiterExerciseItem[] } {
  const items: LimiterExerciseItem[] = [];
  const added = new Set<string>();
  for (const name of option.assistance) {
    const exercise = resolveLimiterExercise(name);
    if (!exercise) continue;
    const en = norm(exercise.name);
    if (added.has(en)) continue;
    added.add(en);
    const group = limiterGroupForExercise(exercise.name) ?? exercise.group ?? 'accessory';
    items.push({
      exercise,
      targetGroup: group,
      optimal: false,
      rationale: `${option.method} → ${exercise.name}: упражнение адресует фактор «${option.label}» (${option.category === 'limiter_hypertrophy' ? 'гипертрофия лимитирующей группы' : LIMITER_CATEGORY_MAP[option.category]?.label ?? option.category}).`,
      protocol: option.protocol,
      pattern: limiterPatternOf(exercise),
    });
  }
  if (items.length > 0) items[0] = { ...items[0], optimal: true };
  return { option, items };
}

/** Протокол опции (для инъекции). */
export function limiterProtocolFor(option: LimiterOption): LimiterProtocol {
  return option.protocol;
}

/** Полная диагностика: все опции движения по категориям с резолвнутыми упражнениями. */
export function analyzeLimiterForLift(lift: Lift): Record<LimiterCategory, { option: LimiterOption; items: LimiterExerciseItem[] }[]> {
  const out = {} as Record<LimiterCategory, { option: LimiterOption; items: LimiterExerciseItem[] }[]>;
  for (const c of LIMITER_CATEGORIES) {
    out[c.id] = limiterOptionsFor(c.id, lift).map(analyzeLimiterOption);
  }
  return out;
}
