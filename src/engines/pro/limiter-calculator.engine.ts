/* ────────────────────────── Классификатор группы ПО ИМЕНИ ──────────────────────────
 * Поле groups СРЦ-пула — коды движений (ЖМ/ПР/ТГ/ОФП/СФП), не мышцы → для групп
 * непригодно («Бицепс стоя» давал chest, «Присед» — back). Классифицируем по имени. */

export function limiterNameGroup(name: string): string {
  const n = norm(name);
  if (/пресс|скруч|планк|анти.?рот|ротац|(?:^|[^а-яё])кор(?:$|[^а-яё])|core/.test(n)) return 'core';
  if (/жим стоя|армейск|махи|дельт|развед.*дельт|плеч|жим.*резин.*стоя/.test(n)) return 'shoulders';
  if (/присед|выпад|жим ногами|разгибани.*ног|сгибани.*ног|икр|гудморнинг|good.?morning|нож|leg|бицепс бедра|бедра/.test(n)) return 'legs';
  if (/жим узким|француз|трицепс|разгибан.*рук|разгибани.*блок|дожим.*узк|отжиман.*брусь|кист|запяст|wrist/.test(n)) return 'arms';
  if (/бицепс(?! бедра)|сгибан.*рук|молот|скотт|брахи|curl|подъем.*бицепс|подъём.*бицепс/.test(n)) return 'arms';
  if (/жим/.test(n)) return 'chest';
  if (/тяга|становая|гипер|наклон|шраги|подтяг|пул|спин/.test(n)) return 'back';
  return 'accessory';
}

/** Группа ПЛ-пула упражнения (для MRV-бюджета/протокола) — по имени, не по groups. */
export function limiterGroupForExercise(name: string): string | null {
  return limiterNameGroup(name);
}

