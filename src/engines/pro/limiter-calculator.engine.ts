export type LimiterCategory =
  | 'speed_strength'
  | 'partial_amplitude'
  | 'stabilization'
  | 'contraction_mode'
  | 'limiter_hypertrophy'
  | 'anthropometry'
  | 'start_specific'
  | 'grip_stiffness'
  | 'coordination'
  | 'endurance_profile';

export interface LimiterProtocol {
  sets: number;
  reps: number;
  pct: number;          // доля от ПМ (0..1.1)
  rir: number;
  tempo?: string;       // «3-1-1-0», «5-0-1-0», ...
  rest?: string;        // «2-3 мин», «15-30 с»
  holdSec?: number;     // для изометрических удержаний
  note?: string;        // особые условия (цепи/резина/упоры/плинты)
}

export interface LimiterOption {
  id: string;
  category: LimiterCategory;
  lift: Lift;
  label: string;           // параметр пользователя
  description: string;     // что означает фактор
  method: string;          // метод + протокольная база
  assistance: string[];    // имена упражнений (резолвятся в пулах)
  protocol: LimiterProtocol;
  rationale: string;       // почему эти упражнения закрывают фактор
  references: string[];    // авторы/годы
}

export interface LimiterCategoryMeta {
  id: LimiterCategory;
  label: string;
  icon: string;
  description: string;
  /** Гипертрофия лимитирующих групп учитывается в MRV-бюджете (как слабые группы). */
  countsTowardMrv: boolean;
}

