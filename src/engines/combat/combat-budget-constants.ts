/**
 * combat-budget-constants.ts — именованные константы бюджета (E1.6).
 *
 * Раньше эти числа стояли инлайном в `combat-builder.engine.ts` (0.08, 12,
 * *3, 100) — по ним нельзя было понять ни смысл, ни источник. Здесь они
 * названы, задокументированы и покрыты source-guard тестом, который не даёт
 * им разъехаться с движком.
 *
 * ЗАБОЖДЕНИЕ О ЧИСЛАХ: это инженерные ограничения модели «сет ↔ минута
 * кондиционирования», а не измерения из публикаций. Для них нет PMID, и
 * выдавать их за научный источник было бы враньём — поэтому источник
 * честно указан как инженерный. Научные пороги единоборств живут отдельно,
 * в `combat-science.ts` (каждый с PMID).
 */

/**
 * Стоимость одной минуты кондиционирования в «зал-сет» при подсчёте бюджета.
 *
 * Смысл: зал-сет и минута зоны-2 — разные единицы, но они конкурируют за
 * один и тот же ресурс (общий объём нагрузки). Правило перевода:
 * ~12 минут зоны-2 эквивалентны одному зал-сету, то есть 1/12 ≈ 0.083.
 * Значение округлено до 0.08 в сторону, безопасную для бюджета: округление
 * вниз не даёт кондиционированию «съесть» лишний сет.
 *
 * ИНЖЕНЕРНАЯ КОНСТАНТА, не измерение. Обоснование — перевод минут в сеты.
 */
export const COND_MIN_TO_SET = 0.08;

/** Минут зоны-2, эквивалентных одному зал-сету (обратная величина к COND_MIN_TO_SET). */
export const SET_EQ_COND_MIN = Math.round(1 / COND_MIN_TO_SET); // 13 (округление от 12.5)

/**
 * Нижний пол недельного бюджета сетов, кг/нед.
 *
 * Смысл: нельзя срезать план до нуля, даже если весь бюджет «съела»
 * кондиционировка или ACWR. 12 сетов — это минимум, при котором ещё
 * сохраняются базовые паттерны для всех мышц.
 *
 * ИНЖЕНЕРНАЯ КОНСТАНТА: нижняя граница сохранения структуры плана, а не
 * физиологический порог.
 */
export const MIN_WEEKLY_SET_BUDGET = 12;

/**
 * Минимальное число подходов у упражнения при обрезке бюджета.
 *
 * Смысл: обрезка не должна оставлять упражнение с одним подходом — такой
 * «сет» не даёт ни стимула, ни смысла. Ниже 2 резать нельзя, поэтому
 * кандидат с 2 сетами просто пропускается (см. цикл обрезки в билдере).
 */
export const MIN_SETS_PER_EXERCISE = 2;

/**
 * Максимус проходов обрезки на одно упражнение.
 *
 * Смысл: страховка от бесконечного цикла. Обрезка идёт кругом по всем
 * упражнениям недели; 3 прохода на упражнение означают «попробовать снять
 * до 3 подходов с него, прежде чем идти к следующему».
 *
 * ИНЖЕНЕРНАЯ КОНСТАНТА: страховка сходимости, не имеет отношения к биологии.
 */
export const MAX_TRIM_PASSES_PER_EX = 3;

/**
 * Жёсткий предел индекса обрезки.
 *
 * Смысл: абсолютный «стоп» для цикла обрезки. При большом превышении бюджета
 * 100 итераций более чем достаточно, чтобы срезать всё, до чего можно
 * добраться; если не хватило — план останется выше бюджета и об этом
 * честно сообщит warning, а не будет крутиться вечно.
 *
 * ИНЖЕНЕРНАЯ КОНСТАНТА: страховка сходимости.
 */
export const MAX_TRIM_ITERATIONS = 100;

/**
 * Стоимость кондиционирования недели в зал-сетах.
 * Единая точка для мест, где нужен одинаковый расчёт (обрезка и warning).
 */
export function conditioningSetCost(sessions: Array<{ durationMin?: number | null } | null | undefined>): number {
  const minutes = (sessions || []).reduce((a, s) => a + (s?.durationMin || 0), 0);
  return Math.round(minutes * COND_MIN_TO_SET);
}

/** Недельный бюджет сетов после вычета кондиционирования, с полом. */
export function effectiveWeeklySetBudget(weeklyBudget: number, condCost: number): number {
  return Math.max(MIN_WEEKLY_SET_BUDGET, weeklyBudget - condCost);
}
