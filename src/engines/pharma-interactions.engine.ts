// ── Course-level special instructions ──
export function getCourseRecommendations(course: CourseEntry[]): CourseRecommendation[] {
  if (!course || !Array.isArray(course) || !course.length) return [];
  const validCourse = course.filter(Boolean);
  const idsArr = validCourse.filter(c => typeof c.substanceId === 'string').map(c => c.substanceId);
  const recs: CourseRecommendation[] = [];

  const hasId = (pattern: string) => idsArr.some(id => id.includes(pattern));
  const totalDose = validCourse.reduce((sum, c) => sum + (c.doseValue || 0), 0);
  const hasOrals = validCourse.some(c => PHARMA_DB[c.substanceId]?.class === 'oral_17aa');
  const hasInjectables = validCourse.some(c => PHARMA_DB[c.substanceId]?.class === 'testosterone' || PHARMA_DB[c.substanceId]?.class === 'trenbolone' || PHARMA_DB[c.substanceId]?.class === 'nandrolone' || PHARMA_DB[c.substanceId]?.class === 'boldenone' || PHARMA_DB[c.substanceId]?.class === 'primobolan' || PHARMA_DB[c.substanceId]?.class === 'drostanolone');
  const hasTrenbolone = hasId('tren');
  const has19Nor = hasId('tren') || hasId('nand') || hasId('deca') || hasId('npp') || hasId('trest');

  // Общие рекомендации для любого курса ААС
  if (hasInjectables || hasOrals) {
    recs.push({
      title: 'Защита органов на курсе (обязательно)',
      items: [
        'Гепатопротекция: TUDCA 500-1000 мг + NAC 1200-1800 мг/сут' + (hasOrals ? ' (дозировки по верхней границе из-за оральных препаратов)' : ''),
        'Кардиопротекция: Омега-3 3000 мг ЭПК+ДГК + CoQ10 200 мг + магний 400 мг/сут',
        'Нефропротекция: гидратация ≥ 3 л воды/сут, астаксантин 12 мг',
        'Контроль АД: телмисартан 40 мг при систолическом ≥ 135 мм рт.ст.',
        'Аспирин 100 мг/сут при HCT > 48% (при отсутствии противопоказаний)',
        'Донорство крови каждые 8-12 нед при HCT > 50%'
      ],
      type: 'info'
    });

    recs.push({
      title: 'План лабораторного мониторинга',
      items: [
        'До курса: ОАК, биохимия (АЛТ/АСТ/ГГТ/билирубин/креатинин), липидограмма, гормоны (общ. тест., E2, ПРЛ, ЛГ, ФСГ, SHBG), ПСА (40+)',
        '4-6 нед курса: ОАК, АЛТ/АСТ, липидограмма, E2, ПРЛ' + (hasTrenbolone ? ' (пролактин каждые 2 нед из-за тренболона)' : '') + (has19Nor ? ' + пролактин' : ''),
        '8-10 нед курса: полный профиль как до курса',
        'Через 4 нед после ПКТ: полный профиль для оценки восстановления оси'
      ],
      type: 'warning'
    });
  }

  // High-dose course
  if (totalDose > 1000) {
    recs.push({
      title: 'Высокодозный курс (>1000 мг/нед) — дополнительные меры',
      items: [
        'Расширенная гепатопротекция: TUDCA 1000 мг + NAC 1800 мг + силимарин 280 мг/сут',
        'Контроль АД ежедневно утром и вечером',
        'Кардио 3-4×/нед по 30-40 мин (ЧСС 120-140 уд/мин)',
        'Анализ на D-димер, фибриноген каждые 4 нед',
        'ЭКГ в покое каждые 8 нед',
        'Рассмотреть добавление небиволола 2.5-5 мг при ЧСС покоя > 80 уд/мин'
      ],
      type: 'critical'
    });
  }

  // Multiple injectables
  const injectableClasses = new Set<string>();
  for (const c of validCourse) {
    const sub = PHARMA_DB[c.substanceId];
    if (sub && ['testosterone', 'trenbolone', 'nandrolone', 'boldenone', 'primobolan', 'drostanolone'].includes(sub.class)) {
      injectableClasses.add(sub.class);
    }
  }
  if (injectableClasses.size >= 3) {
    recs.push({
      title: 'Множественные инъекционные ААС — контроль полицитемии и липидов',
      items: [
        'Риск полицитемии (HCT > 54%) значительно повышен при 3+ инъек-ционных ААС',
        'Контроль HCT, гемоглобина, эритроцитов каждые 2 нед',
        'Липидограмма каждые 4 нед (ожидается ↓ ЛПВП до 70%)',
        'Омега-3 4000 мг ЭПК+ДГК минимум',
        'Цитрусовый бергамот 500 мг 2р/день для контроля липидов',
        'Терапевтическая флеботомия при HCT > 52%'
      ],
      type: 'warning'
    });
  }

  return recs;
}
