            'Высокий риск «трен-кашля»: инъецировать медленно, избегать сосудов, аспирационная проба обязательна.',
            'Обязателен контроль пролактина каждые 2 нед (выше 20 нг/мл → каберголин).',
            'Тренболон не ароматизируется — ИА не нужен, но контроль E2 обязателен (из-за тестостероновой базы).',
