/**
 * support-plan/lab-field-number.ts — число из поля анализов, одно правило на всё
 * приложение.
 *
 * Поле бланка — это строка. Правила её чтения выросли из двух дефектов проходов:
 *  - проход 130: «1+», «2+», «++» — это полоска, а не концентрация. `parseFloat('1+')`
 *    даёт 1, и «+1» белка мочи становился 1 г/л, то есть нефротической протеинурией
 *    из ничего;
 *  - проход 131: бланк печатает «>1000» и «<0.5». `parseFloat` на такой строке даёт
 *    NaN, и анализ пропадал целиком: ферритин «>1000» (перегрузка железом) не давал
 *    ни находки, ни вклада в риск. Границу читаем как её число — так же, как это
 *    делает авто-разбор бланка (`core/lab-auto-parser`: `[<>≤≥]?число`), а интерфейс
 *    говорит об этом баннером «граница вместо числа» (`labBoundNotes`).
 *
 * Проход 136: функция одна и та же для риск-модели (`extractLabValues`) и для
 * плана поддержки (`labSliceToValues`) — раньше правило жило копией в каждом.
 *
 * Проход 141: бланк печатает тысячи с пробелом — «Ферритин 1 000», «Тромбоциты
 * 250 000». `parseFloat` обрывается на первом пробеле, и ферритин 1 000 читался
 * как 1 (то есть как тяжёлый дефицит железа), а не как перегрузка. Разделитель
 * тысяч теперь часть числа: группа из трёх цифр после пробела — это разряды, а не
 * хвост строки. «5 5» (две группы по одной цифре) остаётся прежним чтением: это
 * не число с разрядами, и угадывать за человека нельзя.
 *
 * Проход 155: то же правило читает ручной ввод на экране «Анализы». Там жил свой
 * `parseFloat` (`parseFloat(value) || 0` в `UnifiedLabPanel`, `parseFloat(valStr)`
 * в каталоге и расширенной панели), и он:
 *  - превращал «1 000» в 1, а «5,5» — в 5 (обрезанное число выдавалось за полное);
 *  - терял знак границы: вписанное «>1000» сохранялось как точное 1000, либо не
 *    сохранялось вовсе — молча, с зелёным «Сохранено».
 * Отсюда `labFieldEntry` — запись (число, знак) из одного чтения, и
 * `labFieldUnreadReason` — одна таблица причин «числа нет» на форму калькулятора и
 * на экран анализов.
 */

import type { LabBound } from '../../core/lab-bound';

/** Неразрывные пробелы тоже встречаются в бланках (NBSP, узкий NBSP). */
const THOUSANDS = /^(\d{1,3})((?:[ \u00A0\u202F]\d{3})+(?:[.,]\d+)?)(.*)$/;

export function labFieldNumber(val: unknown): number | undefined {
  if (val === undefined || val === null || val === '') return undefined;
  if (typeof val === 'number') return isNaN(val) ? undefined : val;
  const raw = String(val).trim();
  if (!raw) return undefined;
  // Полоска «1+», «++» — не концентрация (проход 130), даже если рядом есть цифра.
  if (raw.includes('+')) return undefined;

  // Граница «>1000» читается как её число (проход 131), знак при этом отбрасывается.
  // Проход 155: «>=1000»/«≤ 30» пишут так же часто, как «>1000»; знак равенства
  // часть границы, а не числа, и без этого чтения запись терялась целиком.
  const boundMatch = raw.match(/^[<>≤≥]=?\s*(.+)$/);
  const body = boundMatch ? boundMatch[1] : raw;

  // Разряды: пока в остатке стоят группы по три цифры — это одно число.
  let normal = body;
  const grouped = body.match(THOUSANDS);
  if (grouped && !/^\d/.test(grouped[3])) {
    normal = grouped[1] + grouped[2].replace(/[ \u00A0\u202F]/g, '') + grouped[3];
  }

  const n = parseFloat(normal.replace(',', '.'));
  return isNaN(n) ? undefined : n;
}

/**
 * Запись поля целиком: число и знак границы бланка.
 *
 * Проход 155: ручной ввод раньше брал `parseFloat` и терял границу — вписанное
 * «>1000» либо не сохранялось, либо становилось точным 1000, и тренд честно
 * считал разность по числу, которого в бланке не было. Число здесь то же, что у
 * расчёта (`labFieldNumber`), знак — отдельное поле.
 */
export interface LabFieldEntry {
  /** Число, как его читает расчёт (у границы — само число границы). */
  value: number;
  /** Знак границы: «>1000» → `'>'`; у точного числа — `undefined`. */
  bound?: LabBound;
}

export function labFieldEntry(val: unknown): LabFieldEntry | undefined {
  const value = labFieldNumber(val);
  if (value === undefined) return undefined;
  const head = String(val).trim().match(/^([<>≤≥])/);
  if (!head) return { value };
  return { value, bound: head[1] === '>' || head[1] === '≥' ? '>' : '<' };
}

/**
 * Почему в поле нет числа — одной строкой для человека (проход 141/155).
 *
 * Таблица одна: формула калькулятора и экран «Анализы» называют одну и ту же
 * запись одинаково. Раньше причин было две копии, и одна из них обещала
 * «запись сохранена», даже когда экран анализов запись как раз выбрасывал.
 */
export function labFieldUnreadReason(raw: unknown): string {
  const t = String(raw ?? '').trim().toLowerCase();
  if (/^[-–—]$/.test(t)) return 'прочерк в бланке — значения нет';
  if (/^\++$|^\d*\s*\+$/.test(t)) return 'полоска («1+») не переводится в концентрацию';
  if (/^(след|trace)/i.test(t)) return '«следы» — не концентрация, числом не читается';
  if (/^не\s*(обн|найден|опред)/i.test(t) || /^отр/.test(t) || /^neg/i.test(t)) return '«отрицательно» — это не ноль и не число';
  if (/^полож|^posit/i.test(t)) return '«положительно» — это не число, нужна концентрация';
  return 'в поле не число — как результат не читается';
}
