/**
 * tier-reason.ts — текст лаб-ступени без дозы.
 *
 * Этап E2 плана: доза назначения одна — та, что в карточке плана/расписании.
 * `LAB_TIERS` исторически писали свою дозу в прозу («Силимарин 280 мг»), и рядом
 * с карточкой (600 мг) появлялось второе число. Числа в прозе не проверяются и
 * расходятся с реестром; поэтому при сборке причины ступени они снимаются, а
 * дозу показывает карточка.
 *
 * Это НЕ медицинская правка: ни одно число не меняется и не подставляется.
 */

/** Убирает из текста ступени «280 мг», «×2», «↑3 г», «(1000 мг)» и пустые скобки. */
export function stripDosePhrases(text: string): string {
  let out = String(text || '')
    // «×2» / «x2» — кратность, а не доза, но в прозе она рядом с мг.
    .replace(/\s*[×x]\s*\d+(?:[.,]\d+)?/gi, ' ')
    // «↑3 г» / «↑400 мг» — направление и доза одним куском.
    .replace(/[↑↓]\s*\d+(?:[.,]\d+)?\s*(?:мг|мкг|мл|г|МЕ|Ед|млрд\s*КОЕ)?/gi, ' ')
    // «280 мг», «2.5 мг», «2 г», «2000 МЕ», «20 млрд КОЕ».
    // Lookbehind не даёт принять «Омега-3» за дозу «3 г»; `\b` не годится —
    // в JS он ASCII-only, а единицы кириллические.
    .replace(/(?<![\wА-Яа-я-])\d+(?:[.,]\d+)?\s*(?:мг|мкг|мл|г|МЕ|Ед|млрд\s*КОЕ)(?![\wА-Яа-я])/gi, ' ')
    .replace(/\(\s*\)/g, ' ')
    .replace(/\s{2,}/g, ' ')
    .replace(/\s*[—–-]\s*(?=[—–-]|$)/g, ' ')
    .replace(/^\s*[—–-]\s*/, '')
    .trim();
  return out;
}
