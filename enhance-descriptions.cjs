const substanceRegex = /{\s*id:\s*'([^']+)',\s*\n\s*name:\s*'([^']+)',\s*\n\s*categories:\s*\[([^\]]+)\],\s*\n\s*mechanisms:\s*\[([^\]]+)\],\s*\n\s*organs:\s*\[([^\]]+)\],\s*\n\s*deficiency:\s*'([^']*)',\s*\n\s*description:\s*'([^']*)',\s*\n\s*type:\s*'([^']+)'\s*\n\s*}/g;

let match;
const substances = [];
let parsedCount = 0;

while ((match = substanceRegex.exec(d)) !== null) {
  const sub = {
    id: match[1],
    name: match[2],
    categories: match[3].replace(/'/g, '').split(',').map(s => s.trim()).filter(Boolean),
    mechanisms: match[4].replace(/'/g, '').split(',').map(s => s.trim()).filter(Boolean),
    organs: match[5].replace(/'/g, '').split(',').map(s => s.trim()).filter(Boolean),
    deficiency: match[6],
    description: match[7],
    type: match[8],
  };
  substances.push(sub);
  parsedCount++;
}

console.log('Parsed substances:', parsedCount);

// Generate new descriptions
let replaced = 0;
for (const sub of substances) {
  const newDesc = generateDescription(sub);
  if (newDesc !== sub.description) {
    // Escape single quotes for TS
    const escapedOld = sub.description.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const escapedNew = newDesc.replace(/'/g, "\\'");
    
    // Find and replace in the file
    const oldPattern = "description: '" + sub.description.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + "'";
    const newPattern = "description: '" + escapedNew + "'";
    
    const idx = d.indexOf(oldPattern);
    if (idx >= 0) {
      d = d.substring(0, idx) + newPattern + d.substring(idx + oldPattern.length);
      replaced++;
    }
  }
}

console.log('Descriptions replaced:', replaced);

// Write the result
fs.writeFileSync('src/data/support-database.ts', d, 'utf8');
console.log('File saved!');
console.log('New file size:', d.length);
