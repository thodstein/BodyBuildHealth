function generateDescription(sub) {
  // Check for specific description first
  if (SPECIFIC_DESC[sub.id]) return SPECIFIC_DESC[sub.id];
  
  const typeRu = TYPE_RU[sub.type] || sub.type;
  const catRu = sub.categories.map(c => CAT_RU[c] || c).filter(Boolean).slice(0, 2);
  const organRu = sub.organs.map(o => ORGAN_RU[o] || o).filter(Boolean).slice(0, 3);
  const mechRu = sub.mechanisms.slice(0, 2).map(m => {
    // Simple mapping of mechanism ID to Russian
    if (MECH_DESC[m]) return MECH_DESC[m];
    const key = m.replace(/_/g, ' ').toLowerCase();
    return key;
  });
  
  let desc = typeRu;
  if (catRu.length > 0) desc += ' ' + catRu.join(', ');
  desc += ' ' + sub.name + '.';
  if (mechRu.length > 0) desc += ' ' + mechRu[0].charAt(0).toUpperCase() + mechRu[0].slice(1);
  if (mechRu.length > 1) desc += '; ' + mechRu[1];
  desc += '.';
  if (organRu.length > 0) desc += ' Мишени: ' + organRu.join(', ') + '.';
  if (sub.deficiency && sub.deficiency !== 'NONE') {
    desc += ' Дефицит: ' + sub.deficiency.replace(/_/g, ' ').toLowerCase() + '.';
  }
  return desc;
}

