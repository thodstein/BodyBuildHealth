/**
 * pl-fill-groups.mjs — разовый скрипт: заполняет `group` у СТАНДАРТНЫХ упражнений
 * в легаси-циклах `src/data/lms-cycles/*.ts` (долг данных из аудита PL-auto 2026-11).
 *
 * ПРИНЦИПЫ (почему именно так):
 *  • заполняем ТОЛЬКО упражнения с однозначной группой (жим лёжа → Грудь, присед → Ноги…);
 *    армреслинг-специфику (Кисть РР, Пронация СБ, Иммитация верха…) не трогаем —
 *    для неё в таксономии приложения нет крупной группы, а выдумывать нечего;
 *  • группа берётся из той же таксономии, что и остальной каталог
 *    (`RU_TO_EN`: Грудь/Спина/Ноги/Плечи/Руки/Кор) — новых ключей не вводим;
 *  • меняется ТОЛЬКО поле group: ни порядок упражнений, ни %, повторы, подходы
 *    не трогаются (это проверяет страж раскладок через layout-only-отпечаток);
 *  • скрипт идемпотентен: повторный запуск ничего не меняет.
 *
 * Запуск: node scratch/pl-fill-groups.mjs [--dry]
 */
import fs from 'node:fs';
import path from 'node:path';

const DRY = process.argv.includes('--dry');
const DIR = path.join(process.cwd(), 'src', 'data', 'lms-cycles');

/** Упражнение → крупная группа (таксономия приложения). */
const MAP = {
  // Грудь (жимовые движения лёжа/на наклонной)
  'Жим лежа': 'Грудь',
  'Жим средним хватом': 'Грудь',
  'Жим без ног': 'Грудь',
  'Жим на наклонной': 'Грудь',
  'Жим гантелей лежа на накл скамье': 'Грудь',
  'Жим гантелей на наклонной': 'Грудь',
  'Жим гантелей': 'Грудь',
  'Кроссовер': 'Грудь',
  // Плечи
  'Жим стоя': 'Плечи',
  'Подъем гантелей в стороны': 'Плечи',
  'Подъем гантели перед собой': 'Плечи',
  // Ноги
  'Присед': 'Ноги',
  'Присед на груди': 'Ноги',
  'Разгибания ног': 'Ноги',
  'Тяга на прямых ногах': 'Ноги', // РДЛ — бицепс бедра, не спина
  // Спина
  'Тяга верхнего блока': 'Спина',
  'Подтягивание': 'Спина',
  'Тяга гантели в наклоне': 'Спина',
  'Наклоны': 'Спина',
  'Становая тяга': 'Спина',
  // Руки
  'Трицепс на блоке': 'Руки',
  'Французский жим': 'Руки',
  'Разгибания из-за головы': 'Руки',
  'Разгибания с гантелью из-за головы': 'Руки',
  'Строгий подъем на бицепс': 'Руки',
  'Бицепс стоя': 'Руки',
  'Бицепс': 'Руки', // в одном легаси-цикле помечен 'ЖМ', но имя называет мышцу
  'Бицепс стоя со штангой': 'Руки',
  'Молотковые сгибания': 'Руки',
  'Бицепс с гантелями': 'Руки',
  'Концентрированный подъем': 'Руки',
  'Подъем обратным хватом стоя': 'Руки',
};

const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
let filesTouched = 0;
let totalReplaced = 0;
const perFile = [];

for (const file of fs.readdirSync(DIR)) {
  if (!file.endsWith('.ts')) continue;
  const full = path.join(DIR, file);
  const src = fs.readFileSync(full, 'utf8');
  let next = src;
  let replaced = 0;
  for (const [name, group] of Object.entries(MAP)) {
    const re = new RegExp(`(name:\\s*'${esc(name)}',\\s*group:\\s*)''`, 'g');
    const before = next;
    next = next.replace(re, `$1'${group}'`);
    if (before !== next) replaced += (before.match(re) || []).length;
  }
  if (next !== src) {
    filesTouched++;
    totalReplaced += replaced;
    perFile.push(`${file}: +${replaced}`);
    if (!DRY) fs.writeFileSync(full, next, 'utf8');
  }
}

console.log(`${DRY ? '[dry] ' : ''}файлов: ${filesTouched}, вхождений group: ${totalReplaced}`);
console.log(perFile.join('\n'));
