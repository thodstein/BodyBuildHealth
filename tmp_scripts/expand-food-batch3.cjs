function microsToTS(m) {
  if (!m || Object.keys(m).length === 0) return "{}";
  const pairs = [];
  for (const [k, v] of Object.entries(m)) {
    if (v === 0) continue;
    pairs.push(k + ":" + v);
  }
  return "{" + pairs.join(",") + "}";
}

function foodToLine(f) {
  const parts = [
    `{id:"` + f.id + `"`,
    `name:"` + f.name + `"`,
    `category:"` + f.category + `"`,
    `kcal:` + f.kcal,
    `protein:` + f.protein,
    `fat:` + f.fat,
    `carbs:` + f.carbs,
    `fiber:` + f.fiber,
    `gi:` + f.gi,
    `servingSize:"` + f.servingSize + `"`,
    `micros:` + microsToTS(f.micros)
  ];
  return "  " + parts.join(",") + "}";
}

